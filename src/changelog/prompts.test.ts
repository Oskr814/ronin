const { runAgentTask: run } = await import('../core/agent-task.js');
const { changelogTask } = await import('./prompts.js');
// Each task runs through the real runAgentTask, with its checkout and
// `claude -p` mocked: what a test reads is the prompt it was handed.
const runAgentTask = (task: Parameters<typeof changelogTask>[0]) => run(changelogTask(task));
const buildTask = (task: Parameters<typeof changelogTask>[0]) => changelogTask(task).prepare();

